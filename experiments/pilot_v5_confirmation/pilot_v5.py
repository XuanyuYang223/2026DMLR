    expected=statehash(net.state_dict());cp=load(OUT/'smoke'/'resume.pt');n2,_=p.initial(SEEDS[0]);n2.load_state_dict(cp['model']);o2=p.optmake(n2,.0003);o2.load_state_dict(cp['optimizer']);r2=p.restore(cp)
